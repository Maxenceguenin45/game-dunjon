package doc;

/**
 * Package-info pour le jeu de donjon.
 *
 * Structure du projet :
 * - service/ : Services métier (joueur, salles, combat, UI)
 * - controller/ : Contrôleur principal du jeu
 * - animation/ : Effets visuels et animations
 * - util/ : Classes utilitaires et constantes
 * - exception/ : Exceptions personnalisées
 * - model/ : Classes modèles (Joueur, Salle, etc.)
 *
 * Architecture :
 * Le jeu utilise une architecture en couches avec :
 * 1. Couche présentation (UI)
 * 2. Couche contrôleur (GameController)
 * 3. Couche service (logique métier)
 * 4. Couche modèle (entités)
 *
 * Conventions de code :
 * - Utilisation des expressions Yoda (ex: if (null == variable))
 * - Messages et constantes centralisés
 * - Gestion des exceptions personnalisées
 * - Documentation complète avec Javadoc
 */
